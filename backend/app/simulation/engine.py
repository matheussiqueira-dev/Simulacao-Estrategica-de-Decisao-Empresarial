"""Reference implementation of the simulation engine.

The deployed app runs the TypeScript port (frontend/src/lib/simulation/engine.ts).
Both are tested against fixtures/simulation-golden.json, generated by
scripts/generate_golden.py; change a formula in both places and regenerate.

One effective demand (monthly demand x price factor) drives both the KPIs and the
projection: the monthly profit is the first projected month and the annual profit
is the sum of the next 12 months.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from datetime import date

from app.simulation.schemas import SimulationInput, SimulationResult

BASE_SALARY = 4200.0
WORKING_CAPITAL_RATIO = 0.12
DEBT = 150_000.0
DEPRECIATION_RATE = 0.05
SEASONALITY_AMPLITUDE = 0.08
MIN_PRICE_FACTOR = 0.6
MAX_PRICE_FACTOR = 1.3
MONTHS_PER_YEAR = 12


def _clip(value: float, low: float, high: float) -> float:
    return min(max(value, low), high)


def _month_labels(start: date, count: int) -> list[str]:
    """ISO "YYYY-MM" labels for `count` months starting at `start`'s month."""
    labels = []
    for offset in range(count):
        month_index = start.month - 1 + offset
        labels.append(f"{start.year + month_index // 12:04d}-{month_index % 12 + 1:02d}")
    return labels


@dataclass(frozen=True)
class _Month:
    revenue: float
    profit: float


def _operating_costs(data: SimulationInput) -> float:
    return data.employees * BASE_SALARY + data.fixed_cost + data.marketing_spend


def _interest_expense(data: SimulationInput) -> float:
    return DEBT * data.interest_rate / 12


def price_factor(data: SimulationInput) -> float:
    """Demand multiplier from the price: above 100, sensitive markets buy less."""
    return _clip(
        1 - data.price_sensitivity * ((data.price - 100) / 100),
        MIN_PRICE_FACTOR,
        MAX_PRICE_FACTOR,
    )


def _month(data: SimulationInput, units: float) -> _Month:
    revenue = data.price * units
    profit_before_tax = (
        revenue - data.variable_cost * units - _operating_costs(data) - _interest_expense(data)
    )
    taxes = max(profit_before_tax, 0) * data.tax_rate
    return _Month(revenue=revenue, profit=profit_before_tax - taxes)


class SimulationEngine:
    """Estimates profit, cash flow, growth and risk from the input variables."""

    def run(self, data: SimulationInput, start: date | None = None) -> SimulationResult:
        effective_demand = data.demand * price_factor(data)

        marketing_factor = math.log1p(data.marketing_spend) / 10_000
        price_penalty = data.price_sensitivity * max((data.price - 100) / 100, 0)
        churn_penalty = data.churn_rate * 0.6
        monthly_growth = _clip(0.01 + marketing_factor - price_penalty - churn_penalty, -0.1, 0.25)

        # Projected long enough to also cover a full year for the annual figure.
        projected = max(data.period_months, MONTHS_PER_YEAR)
        months: list[_Month] = []
        for idx in range(projected):
            seasonality = 1 + SEASONALITY_AMPLITUDE * math.sin(2 * math.pi * idx / 12)
            # A shrinking market stops at zero: demand never goes negative.
            trend = max(1 + monthly_growth * idx, 0)
            months.append(_month(data, effective_demand * trend * seasonality))

        current = months[0]
        depreciation = data.fixed_cost * DEPRECIATION_RATE
        working_capital_change = current.revenue * WORKING_CAPITAL_RATIO
        cash_flow = current.profit + depreciation - working_capital_change / data.period_months

        contribution_margin = data.price - data.variable_cost
        breakeven_units = (_operating_costs(data) + _interest_expense(data)) / max(
            contribution_margin, 1e-3
        )
        safety_margin = (effective_demand - breakeven_units) / max(effective_demand, 1e-3)
        risk_index = _clip(1 - safety_margin, 0, 1)

        shown = months[: data.period_months]
        annual_profit = sum(month.profit for month in months[:MONTHS_PER_YEAR])

        return SimulationResult(
            monthly_profit=round(current.profit, 2),
            annual_profit=round(annual_profit, 2),
            cash_flow=round(cash_flow, 2),
            safety_margin=round(safety_margin, 3),
            growth_rate=round(monthly_growth * 12, 3),
            risk_index=round(risk_index, 3),
            revenue_series=[round(month.revenue, 2) for month in shown],
            profit_series=[round(month.profit, 2) for month in shown],
            month_labels=_month_labels(start or date.today(), data.period_months),
        )
